class SocialBenefitsDatabase {
  static List<SocialBenefit> getBenefitsByCountry(String countryCode) {
    return _allBenefits
        .where((b) => b.countryCode == countryCode.toUpperCase())
        .toList();
  }

  static List<SocialBenefit> getBenefitsByType(String type) {
    return _allBenefits.where((b) => b.type == type).toList();
  }

  static List<SocialBenefit> getAsylumSeekerBenefits(String countryCode) {
    return _allBenefits
        .where((b) =>
            b.countryCode == countryCode.toUpperCase() &&
            b.availableToAsylumSeekers)
        .toList();
  }

  static List<SocialBenefit> searchBenefits(String query) {
    final q = query.toLowerCase();
    return _allBenefits
        .where((b) =>
            b.benefitName.toLowerCase().contains(q) ||
            b.type.toLowerCase().contains(q) ||
            b.country.toLowerCase().contains(q) ||
            b.eligibility.toLowerCase().contains(q))
        .toList();
  }

  static CountryBenefitsSummary? getCountrySummary(String countryCode) {
    final code = countryCode.toUpperCase();
    return _countrySummaries.where((s) => s.countryCode == code).firstOrNull;
  }

  static List<String> getAllCountryCodes() {
    return _countrySummaries.map((s) => s.countryCode).toList();
  }

  static List<CountryBenefitsSummary> get allSummaries => _countrySummaries;

