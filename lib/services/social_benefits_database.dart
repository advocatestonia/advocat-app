class SocialBenefit {
  final String country;
  final String countryCode;
  final String benefitName;
  final String nameLocal;
  final String type;
  final String eligibility;
  final String amount;
  final String howToApply;
  final String authority;
  final String? phone;
  final String? website;
  final String waitingPeriod;
  final bool availableToAsylumSeekers;
  final bool availableToUndocumented;
  final String legalBasis;
  final String currency;
  final List<String> requiredDocuments;

  const SocialBenefit({
    required this.country,
    required this.countryCode,
    required this.benefitName,
    required this.nameLocal,
    required this.type,
    required this.eligibility,
    required this.amount,
    required this.howToApply,
    required this.authority,
    this.phone,
    this.website,
    required this.waitingPeriod,
    required this.availableToAsylumSeekers,
    required this.availableToUndocumented,
    required this.legalBasis,
    this.currency = 'EUR',
    this.requiredDocuments = const [],
  });

  Map<String, dynamic> toMap() => {
    'country': country,
    'countryCode': countryCode,
    'benefitName': benefitName,
    'nameLocal': nameLocal,
    'type': type,
    'eligibility': eligibility,
    'amount': amount,
    'howToApply': howToApply,
    'authority': authority,
    'phone': phone,
    'website': website,
    'waitingPeriod': waitingPeriod,
    'availableToAsylumSeekers': availableToAsylumSeekers,
    'availableToUndocumented': availableToUndocumented,
    'legalBasis': legalBasis,
    'currency': currency,
    'requiredDocuments': requiredDocuments,
  };
}

