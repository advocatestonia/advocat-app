class WorkPermitType {
  final String country;
  final String countryCode;
  final String name;
  final String nameEn;
  final String category;
  final String description;
  final List<String> requirements;
  final String applicationAuthority;
  final String? applicationFee;
  final int processingWeeks;
  final bool familyIncluded;
  final String legalBasis;
  final String? salaryThreshold;
  final bool laborMarketTestRequired;
  final String? validityPeriod;
  final String? renewalInfo;
  final String? officialUrl;

  const WorkPermitType({
    required this.country,
    required this.countryCode,
    required this.name,
    required this.nameEn,
    required this.category,
    required this.description,
    required this.requirements,
    required this.applicationAuthority,
    this.applicationFee,
    required this.processingWeeks,
    required this.familyIncluded,
    required this.legalBasis,
    this.salaryThreshold,
    required this.laborMarketTestRequired,
    this.validityPeriod,
    this.renewalInfo,
    this.officialUrl,
  });
}

