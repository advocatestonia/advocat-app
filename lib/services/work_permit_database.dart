class WorkPermitDatabase {
  static final WorkPermitDatabase _instance = WorkPermitDatabase._internal();
  factory WorkPermitDatabase() => _instance;
  WorkPermitDatabase._internal();

  /// Get all permits for a specific country
  List<WorkPermitType> getByCountry(String countryCode) {
    return _allPermits
        .where((p) => p.countryCode == countryCode.toUpperCase())
        .toList();
  }

  /// Get all permits of a specific category across EU
  List<WorkPermitType> getByCategory(String category) {
    return _allPermits.where((p) => p.category == category).toList();
  }

  /// Get all EU Blue Card implementations
  List<WorkPermitType> getBlueCards() {
    return getByCategory(PermitCategory.euBlueCard);
  }

  /// Search permits by keyword
  List<WorkPermitType> search(String query) {
    final q = query.toLowerCase();
    return _allPermits.where((p) {
      return p.country.toLowerCase().contains(q) ||
          p.nameEn.toLowerCase().contains(q) ||
          p.name.toLowerCase().contains(q) ||
          p.description.toLowerCase().contains(q) ||
          p.category.toLowerCase().contains(q);
    }).toList();
  }

  /// Get all countries
  List<String> get countries => _allPermits.map((p) => p.country).toSet().toList()..sort();

  /// Get all permits
  List<WorkPermitType> get allPermits => List.unmodifiable(_allPermits);

  /// Compare Blue Card salary thresholds across EU
  Map<String, String?> blueCardSalaryComparison() {
    final blueCards = getBlueCards();
    return {for (var bc in blueCards) bc.countryCode: bc.salaryThreshold};
  }

